def _psycopg() -> Any:
    try:
        import psycopg
    except ImportError as e:  # pragma: no cover - depends on the environment
        raise ImportError(
            "PostgresLedger needs psycopg 3: install the 'postgres' extra"
            " (pip install 'agentline[postgres]' or uv sync --extra postgres)"
        ) from e
    return psycopg


def _lock_key(purpose: str, schema: str | None) -> int:
    """A stable signed 64-bit advisory-lock key, distinct per schema."""
    digest = hashlib.sha256(f"agentline:{purpose}:{schema or ''}".encode()).digest()
    return int.from_bytes(digest[:8], "big", signed=True)


def redact_dsn(dsn: str) -> str:
    """The DSN with any password replaced by `***` (for logs and CLI output)."""
    if "://" not in dsn:  # key=value form
        return re.sub(r"(password\s*=\s*)('[^']*'|\S+)", r"\1***", dsn)
    parts = urlsplit(dsn)
    if parts.password is None:
        return dsn
    host = parts.hostname or ""
    if parts.port:
        host = f"{host}:{parts.port}"
    netloc = f"{parts.username or ''}:***@{host}"
    return urlunsplit((parts.scheme, netloc, parts.path, parts.query, parts.fragment))


class _PgJournalTasks:
    def add_journal(
        self,
        run_id: str,
        kind: str,
        message: str,
        *,
        execution_id: str | None = None,
        node_id: str | None = None,
        iteration: int = 1,
        task: int | None = None,
        detail: dict[str, Any] | None = None,
        at: float | None = None,
    ) -> int:
        row = self._q(  # type: ignore[attr-defined]
            "INSERT INTO journal (at, run_id, execution_id, node_id, iteration, task, kind,"
            " message, detail_json) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s) RETURNING id",
            (
                time.time() if at is None else at,
                run_id,
                execution_id,
                node_id,
                iteration,
                task,
                kind,
                message,
                self._j(detail or {}),  # type: ignore[attr-defined]
            ),
        ).fetchone()
        return int(row["id"])

    def list_journal(
        self, run_id: str, node_id: str | None = None, limit: int = 5000
    ) -> list[JournalEntry]:
        if node_id is None:
            rows = self._q(  # type: ignore[attr-defined]
                "SELECT * FROM journal WHERE run_id = %s ORDER BY id LIMIT %s", (run_id, limit)
            ).fetchall()
        else:
            rows = self._q(  # type: ignore[attr-defined]
                "SELECT * FROM journal WHERE run_id = %s AND node_id = %s ORDER BY id LIMIT %s",
                (run_id, node_id, limit),
            ).fetchall()
        out = []
        for r in rows:
            d = dict(r)
            d["detail"] = d.pop("detail_json") or {}
            out.append(JournalEntry(**d))
        return out

    def add_run_message(
        self,
        run_id: str,
        role: str,
        text: str,
        *,
        via: str | None = None,
        detail: dict[str, Any] | None = None,
        at: float | None = None,
    ) -> int:
        row = self._q(  # type: ignore[attr-defined]
            "INSERT INTO run_messages (run_id, at, role, text, via, detail_json)"
            " VALUES (%s, %s, %s, %s, %s, %s) RETURNING id",
            (run_id, time.time() if at is None else at, role, text, via, self._j(detail or {})),  # type: ignore[attr-defined]
        ).fetchone()
        return int(row["id"])

    def list_run_messages(self, run_id: str, after: int = 0, limit: int = 1000) -> list[RunMessage]:
        rows = self._q(  # type: ignore[attr-defined]
            "SELECT * FROM run_messages WHERE run_id = %s AND id > %s ORDER BY id LIMIT %s",
            (run_id, after, limit),
        ).fetchall()
        out = []
        for r in rows:
            d = dict(r)
            d["detail"] = d.pop("detail_json") or {}
            out.append(RunMessage(**d))
        return out

    def update_run_message(self, message_id: int, detail: dict[str, Any]) -> None:
        self._q(  # type: ignore[attr-defined]
            "UPDATE run_messages SET detail_json = %s WHERE id = %s",
            (self._j(detail), message_id),  # type: ignore[attr-defined]
        )

    def put_task(self, task: TaskRecord) -> None:
        self._q(  # type: ignore[attr-defined]
            "INSERT INTO tasks (execution_id, idx, run_id, node_id, iteration, status, attempts,"
            " item_json, result_json, error, started_at, finished_at)"
            " VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)"
            " ON CONFLICT (execution_id, idx) DO UPDATE SET status = EXCLUDED.status,"
            " attempts = EXCLUDED.attempts, item_json = EXCLUDED.item_json,"
            " result_json = EXCLUDED.result_json, error = EXCLUDED.error,"
            " started_at = EXCLUDED.started_at, finished_at = EXCLUDED.finished_at",
            (
                task.execution_id,
                task.idx,
                task.run_id,
                task.node_id,
                task.iteration,
                task.status,
                task.attempts,
                self._j(task.item),  # type: ignore[attr-defined]
                self._j(task.result),  # type: ignore[attr-defined]
                task.error,
                task.started_at,
                task.finished_at,
            ),
        )

    def list_tasks(self, run_id: str, execution_id: str | None = None) -> list[TaskRecord]:
        if execution_id is None:
            rows = self._q(  # type: ignore[attr-defined]
                "SELECT * FROM tasks WHERE run_id = %s ORDER BY execution_id, idx", (run_id,)
            ).fetchall()
        else:
            rows = self._q(  # type: ignore[attr-defined]
                "SELECT * FROM tasks WHERE run_id = %s AND execution_id = %s ORDER BY idx",
                (run_id, execution_id),
            ).fetchall()
        out = []
        for r in rows:
            d = dict(r)
            d["item"] = d.pop("item_json")
            d["result"] = d.pop("result_json")
            out.append(TaskRecord(**d))
        return out


class PostgresTx(_PgJournalTasks):
    def __init__(self, conn: Any, lock_key: int) -> None:
        self.conn = conn  # not `c`: callers probe `tx.c` for SQLite-only fast paths
        self._lock_key = lock_key
        self._serialized = False
        self._jsonb = _psycopg().types.json.Jsonb

    def _serialize(self) -> None:
        """Take the ledger's transaction lock once, on the first operation that needs it."""
        if not self._serialized:
            self.conn.execute("SELECT pg_advisory_xact_lock(%s::bigint)", (self._lock_key,))
            self._serialized = True

    def _q(self, sql: str, params: Any = ()) -> Any:
        self._serialize()
        return self.conn.execute(sql, params)

    def _j(self, value: Any) -> Any:
        return self._jsonb(value)

    # -- runs -----------------------------------------------------------------------------
    @staticmethod
    def _run(row: dict[str, Any] | None) -> Run | None:
        if row is None:
            return None
        d = dict(row)
        d["payload"] = d.pop("payload_json")
        return Run(**d)

    def insert_run(self, run: Run) -> None:
        self._q(
            "INSERT INTO runs (id, flow, flow_hash, payload_json, status, dedupe_key, budget_usd,"
            " cost_usd, error, created_at, updated_at)"
            " VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)",
            (
                run.id,
                run.flow,
                run.flow_hash,
                self._j(run.payload),
                run.status,
                run.dedupe_key,
                run.budget_usd,
                run.cost_usd,
                run.error,
                run.created_at,
                run.updated_at,
            ),
        )

    def get_run(self, run_id: str) -> Run | None:
        return self._run(self._q("SELECT * FROM runs WHERE id = %s", (run_id,)).fetchone())

    def get_run_by_dedupe(self, dedupe_key: str) -> Run | None:
        row = self._q("SELECT * FROM runs WHERE dedupe_key = %s", (dedupe_key,)).fetchone()
        return self._run(row)

    def update_run(self, run_id: str, **fields_: Any) -> None:
        fields_.setdefault("updated_at", time.time())
        if "payload" in fields_:
            fields_["payload_json"] = self._j(fields_.pop("payload"))
        cols = ", ".join(f"{k} = %s" for k in fields_)
        self._q(f"UPDATE runs SET {cols} WHERE id = %s", (*fields_.values(), run_id))

    def list_runs(self, status: str | None = None, limit: int = 100) -> list[Run]:
        if status:
            cur = self._q(
                "SELECT * FROM runs WHERE status = %s ORDER BY created_at DESC, id LIMIT %s",
                (status, limit),
            )
        else:
            cur = self._q("SELECT * FROM runs ORDER BY created_at DESC, id LIMIT %s", (limit,))
        return [r for r in (self._run(x) for x in cur.fetchall()) if r]

    def add_cost(
        self,
        run_id: str,
        execution_id: str,
        attempt: int,
        usd: float,
        note: str,
        *,
        touch: bool = True,
        on_execution: bool = True,
    ) -> float:
        now = time.time()
        self._q(
            "INSERT INTO costs (run_id, execution_id, attempt, usd, note, at)"
            " VALUES (%s,%s,%s,%s,%s,%s)",
            (run_id, execution_id, attempt, usd, note, now),
        )
        if on_execution:
            self._q(
                "UPDATE executions SET cost_usd = cost_usd + %s WHERE id = %s", (usd, execution_id)
            )
        row = self._q(
            "UPDATE runs SET cost_usd = cost_usd + %s, updated_at = CASE WHEN %s THEN %s"
            " ELSE updated_at END WHERE id = %s RETURNING cost_usd",
            (usd, touch, now, run_id),
        ).fetchone()
        return float(row["cost_usd"]) if row else 0.0

    def list_costs(self, run_id: str) -> list[dict[str, Any]]:
        cur = self._q("SELECT * FROM costs WHERE run_id = %s ORDER BY id", (run_id,))
        return [dict(r) for r in cur.fetchall()]

    # -- executions -----------------------------------------------------------------------
    @staticmethod
    def _exec(row: dict[str, Any] | None) -> Execution | None:
        if row is None:
            return None
        d = dict(row)
        d["detail"] = d.pop("detail_json") or {}
        return Execution(**d)

    def insert_execution(self, ex: Execution) -> None:
        values = {k: getattr(ex, k) for k in _EXEC_COLUMNS}
        values["detail_json"] = self._j(values.pop("detail"))
        cols = ", ".join(values)
        marks = ", ".join("%s" for _ in values)
        self._q(f"INSERT INTO executions ({cols}) VALUES ({marks})", tuple(values.values()))

    def get_execution(self, exec_id: str) -> Execution | None:
        row = self._q(f"SELECT {_EXEC_SELECT} FROM executions WHERE id = %s", (exec_id,)).fetchone()
        return self._exec(row)

    def update_execution(
        self,
        exec_id: str,
        *,
        expect_status: str | None = None,
        expect_epoch: int | None = None,
        **fields_: Any,
    ) -> bool:
        if "detail" in fields_:
            fields_["detail_json"] = self._j(fields_.pop("detail"))
        cols = ", ".join(f"{k} = %s" for k in fields_)
        where = "id = %s"
        params: list[Any] = [*fields_.values(), exec_id]
        if expect_status is not None:
            where += " AND status = %s"
            params.append(expect_status)
        if expect_epoch is not None:
            where += " AND lease_epoch = %s"
            params.append(expect_epoch)
        cur = self._q(f"UPDATE executions SET {cols} WHERE {where}", params)
        return bool(cur.rowcount == 1)

    def _execs(self, where: str, params: Any, order: str = "") -> list[Execution]:
        cur = self._q(f"SELECT {_EXEC_SELECT} FROM executions WHERE {where} {order}", params)
        return [e for e in (self._exec(r) for r in cur.fetchall()) if e]

    def list_executions(self, run_id: str) -> list[Execution]:
        return self._execs("run_id = %s", (run_id,), "ORDER BY created_at, iteration, id")

    def open_execution(self, run_id: str, node_id: str) -> Execution | None:
        found = self._execs(
            "run_id = %s AND node_id = %s AND status = 'pending'",
            (run_id, node_id),
            "ORDER BY iteration DESC LIMIT 1",
        )
        return found[0] if found else None

    def max_iteration(self, run_id: str, node_id: str) -> int:
        row = self._q(
            "SELECT MAX(iteration) AS m FROM executions WHERE run_id = %s AND node_id = %s",
            (run_id, node_id),
        ).fetchone()
        return int(row["m"] or 0)

    def claim_next(self, owner: str, now: float, lease_ttl: float) -> Execution | None:
        # No transaction lock here (unless an earlier operation took it): the row lock from
        # FOR UPDATE SKIP LOCKED is enough, and concurrent claimers skip each other's rows.
        cur = self.conn.execute(
            "WITH next AS ("
            " SELECT id FROM executions"
            " WHERE status IN ('ready', 'failed') AND next_attempt_at <= %s"
            " ORDER BY next_attempt_at, created_at, id LIMIT 1"
            " FOR UPDATE SKIP LOCKED)"
            " UPDATE executions AS e SET status = 'running', lease_owner = %s,"
            " lease_expires = %s, lease_epoch = e.lease_epoch + 1, started_at = %s"
            " FROM next WHERE e.id = next.id"
            f" RETURNING {', '.join('e.' + c for c in _EXEC_SELECT.split(', '))}",
            (now, owner, now + lease_ttl, now),
        )
        return self._exec(cur.fetchone())

    def expired_leases(self, now: float) -> list[Execution]:
        return self._execs(
            "status = 'running' AND lease_expires < %s", (now,), "ORDER BY lease_expires, id"
        )

    def waiting_by_key(self, correlation_key: str) -> list[Execution]:
        return self._execs(
            "status = 'waiting' AND correlation_key = %s", (correlation_key,), "ORDER BY id"
        )

    def count_active(self) -> int:
        row = self._q(
            "SELECT COUNT(*) AS n FROM executions WHERE status IN ('ready', 'running', 'failed')"
        ).fetchone()
        return int(row["n"])

    # -- loops ----------------------------------------------------------------------------
    def loop_count(self, run_id: str, edge_id: str) -> int:
        row = self._q(
            "SELECT count FROM loop_counts WHERE run_id = %s AND edge_id = %s", (run_id, edge_id)
        ).fetchone()
        return int(row["count"]) if row else 0

    def inc_loop_count(self, run_id: str, edge_id: str) -> int:
        row = self._q(
            "INSERT INTO loop_counts (run_id, edge_id, count) VALUES (%s, %s, 1)"
            " ON CONFLICT (run_id, edge_id) DO UPDATE SET count = loop_counts.count + 1"
            " RETURNING count",
            (run_id, edge_id),
        ).fetchone()
        return int(row["count"])

    # -- effects --------------------------------------------------------------------------
    @staticmethod
    def _effect(row: dict[str, Any] | None) -> Effect | None:
        if row is None:
            return None
        d = dict(row)
        d["result"] = d.pop("result_json")
        d["advice"] = d.pop("advice_json")
        return Effect(**d)

    def get_effect(self, run_id: str, node_id: str, iteration: int, name: str) -> Effect | None:
        row = self._q(
            "SELECT * FROM effects"
            " WHERE run_id = %s AND node_id = %s AND iteration = %s AND name = %s",
            (run_id, node_id, iteration, name),
        ).fetchone()
        return self._effect(row)

    def put_effect(self, effect: Effect) -> None:
        self._q(
            "INSERT INTO effects (run_id, node_id, iteration, name, status, idempotency_key,"
            " result_json, advice_json, updated_at) VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s)"
            " ON CONFLICT (run_id, node_id, iteration, name) DO UPDATE SET"
            " status = excluded.status, idempotency_key = excluded.idempotency_key,"
            " result_json = excluded.result_json,"
            " advice_json = excluded.advice_json, updated_at = excluded.updated_at",
            (
                effect.run_id,
                effect.node_id,
                effect.iteration,
                effect.name,
                effect.status,
                effect.idempotency_key,
                None if effect.result is None else self._j(effect.result),
                None if effect.advice is None else self._j(effect.advice),
                effect.updated_at or time.time(),
            ),
        )

    def list_effects(self, run_id: str) -> list[Effect]:
        rows = self._q(
            "SELECT * FROM effects WHERE run_id = %s ORDER BY updated_at, node_id, iteration, name",
            (run_id,),
        ).fetchall()
        return [e for e in (self._effect(r) for r in rows) if e]

    # -- blobs ----------------------------------------------------------------------------
    def put_blob(self, data: bytes) -> str:
        ref = content_hash(data)
        self._q(
            "INSERT INTO blobs (ref, data, size, created_at) VALUES (%s, %s, %s, %s)"
            " ON CONFLICT (ref) DO NOTHING",
            (ref, bytes(data), len(data), time.time()),
        )
        return ref

    def get_blob(self, ref: str) -> bytes | None:
        row = self._q("SELECT data FROM blobs WHERE ref = %s", (ref,)).fetchone()
        return bytes(row["data"]) if row else None

    # -- artifacts ------------------------------------------------------------------------
    def put_artifact(self, artifact: Artifact) -> None:
        a = artifact
        self._q(
            "INSERT INTO artifacts (hash, kind, media_type, size, summary, storage, path,"
            " created_at) VALUES (%s,%s,%s,%s,%s,%s,%s,%s) ON CONFLICT (hash) DO NOTHING",
            (
                a.hash,
                a.kind,
                a.media_type,
                a.size,
                a.summary,
                a.storage,
                a.path,
                a.created_at or time.time(),
            ),
        )

    def get_artifact(self, hash: str) -> Artifact | None:
        row = self._q("SELECT * FROM artifacts WHERE hash = %s", (hash,)).fetchone()
        return Artifact(**dict(row)) if row else None

    def add_artifact_link(self, link: ArtifactLink) -> None:
        k = link
        self._q(
            "INSERT INTO artifact_links (run_id, execution_id, node_id, iteration, name, hash,"
            " direction, at, source_execution_id) VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s)"
            " ON CONFLICT (execution_id, name, direction, hash) DO NOTHING",
            (
                k.run_id,
                k.execution_id,
                k.node_id,
                k.iteration,
                k.name,
                k.hash,
                k.direction,
                k.at or time.time(),
                k.source_execution_id,
            ),
        )

    def list_artifact_links(self, run_id: str) -> list[ArtifactLink]:
        rows = self._q(
            "SELECT run_id, execution_id, node_id, iteration, name, hash, direction, at,"
            " source_execution_id FROM artifact_links WHERE run_id = %s ORDER BY id",
            (run_id,),
        ).fetchall()
        return [ArtifactLink(**dict(r)) for r in rows]

    # -- events ---------------------------------------------------------------------------
    def insert_event(self, correlation_key: str, payload: Any, now: float) -> int:
        row = self._q(
            "INSERT INTO events (correlation_key, payload_json, received_at)"
            " VALUES (%s, %s, %s) RETURNING id",
            (correlation_key, self._j(payload), now),
        ).fetchone()
        return int(row["id"])

    def unconsumed_event(self, correlation_key: str, since: float = 0.0) -> Event | None:
        row = self._q(
            "SELECT * FROM events WHERE correlation_key = %s AND consumed_by IS NULL"
            " AND received_at >= %s ORDER BY id LIMIT 1",
            (correlation_key, since),
        ).fetchone()
        if row is None:
            return None
        d = dict(row)
        d["payload"] = d.pop("payload_json")
        return Event(**d)

    def consume_event(self, event_id: int, consumer: str) -> None:
        self._q("UPDATE events SET consumed_by = %s WHERE id = %s", (consumer, event_id))

    # -- deliveries -----------------------------------------------------------------------
    def claim_delivery(self, source: str, delivery_id: str, now: float) -> bool:
        cur = self._q(
            "INSERT INTO webhook_deliveries (source, delivery_id, received_at)"
            " VALUES (%s, %s, %s) ON CONFLICT (source, delivery_id) DO NOTHING",
            (source, delivery_id, now),
        )
        return bool(cur.rowcount == 1)

    # -- audit ----------------------------------------------------------------------------
    def add_audit(
        self,
        actor: str,
        action: str,
        run_id: str | None = None,
        node_id: str | None = None,
        detail: dict[str, Any] | None = None,
        at: float | None = None,
    ) -> int:
        row = self._q(
            "INSERT INTO audit_log (at, actor, action, run_id, node_id, detail_json)"
            " VALUES (%s, %s, %s, %s, %s, %s) RETURNING id",
            (
                time.time() if at is None else at,
                actor,
                action,
                run_id,
                node_id,
                self._j(detail or {}),
            ),
        ).fetchone()
        return int(row["id"])

    def list_audit(self, run_id: str | None = None, limit: int = 1000) -> list[AuditEntry]:
        if run_id is None:
            rows = self._q(
                "SELECT * FROM (SELECT * FROM audit_log ORDER BY id DESC LIMIT %s) AS latest"
                " ORDER BY id",
                (limit,),
            ).fetchall()
        else:
            rows = self._q(
                "SELECT * FROM audit_log WHERE run_id = %s ORDER BY id LIMIT %s", (run_id, limit)
            ).fetchall()
        out = []
        for r in rows:
            d = dict(r)
            d["detail"] = d.pop("detail_json") or {}
            out.append(AuditEntry(**d))
        return out


class PostgresLedger:
    """`PostgresLedger("postgresql://user:pass@host/db")`. One connection per thread (the
    engine calls the ledger from `asyncio.to_thread`), opened lazily and reopened after a
    connection failure. `schema` puts every table in that Postgres schema (created if
    missing), e.g. to give each test or each tenant its own namespace."""

    def __init__(self, dsn: str, *, schema: str | None = None, connect_timeout: int = 10) -> None:
        self._pg = _psycopg()
        self.dsn = dsn
        self.schema = schema
        self.connect_timeout = connect_timeout
        self._tx_lock_key = _lock_key("tx", schema)
        self._local = threading.local()
        self._conns: list[Any] = []
        self._conns_lock = threading.Lock()
        self._closed = False
        self._create_schema()

    def __repr__(self) -> str:
        return f"PostgresLedger({redact_dsn(self.dsn)!r}, schema={self.schema!r})"

    # -- connections ----------------------------------------------------------------------
    def _connect(self) -> Any:
        from psycopg.rows import dict_row

        conn = self._pg.connect(
            self.dsn, autocommit=True, row_factory=dict_row, connect_timeout=self.connect_timeout
        )
        if self.schema:
            sql = self._pg.sql
            conn.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(self.schema)))
        return conn

    def _conn(self) -> Any:
        if self._closed:
            raise RuntimeError("PostgresLedger is closed")
        conn = getattr(self._local, "conn", None)
        if conn is None or conn.closed:
            conn = self._connect()
            self._local.conn = conn
            with self._conns_lock:
                self._conns.append(conn)
        return conn

    def _discard(self, conn: Any) -> None:
        if getattr(self._local, "conn", None) is conn:
            self._local.conn = None
        with self._conns_lock:
            if conn in self._conns:
                self._conns.remove(conn)
        with suppress(Exception):  # best effort
            conn.close()

    def _create_schema(self) -> None:
        sql = self._pg.sql
        conn = self._conn()
        with conn.transaction():
            # Concurrent CREATE TABLE IF NOT EXISTS can still collide in the catalog: serialize.
            conn.execute("SELECT pg_advisory_xact_lock(%s::bigint)", (_lock_key("schema", None),))
            if self.schema:
                conn.execute(
                    sql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(sql.Identifier(self.schema))
                )
            for stmt in SCHEMA:
                conn.execute(stmt)
            row = conn.execute("SELECT MAX(version) AS v FROM schema_version").fetchone()
            current = row["v"] if row else None
            if current is not None and current > SCHEMA_VERSION:
                raise RuntimeError(
                    f"ledger schema version {current} is newer than this agentline"
                    f" ({SCHEMA_VERSION}); upgrade agentline"
                )
            conn.execute(
                "INSERT INTO schema_version (version, applied_at) VALUES (%s, %s)"
                " ON CONFLICT (version) DO NOTHING",
                (SCHEMA_VERSION, time.time()),
            )

    # -- protocol -------------------------------------------------------------------------
    @contextmanager
    def tx(self) -> Iterator[PostgresTx]:
        conn = self._conn()
        try:
            with conn.transaction():
                yield PostgresTx(conn, self._tx_lock_key)
        except self._pg.OperationalError:
            if conn.broken or conn.closed:
                self._discard(conn)  # the next tx on this thread reconnects
            raise

    def close(self) -> None:
        self._closed = True
        with self._conns_lock:
            conns, self._conns = self._conns, []
        for conn in conns:
            with suppress(Exception):  # best effort
                conn.close()
