"""Postgres ledger: many worker processes on many hosts share one database.

Concurrency model (docs/phase-8a.md):

- Claims are lock-free with respect to each other: `claim_next` is one
  `UPDATE ... FROM (SELECT ... FOR UPDATE SKIP LOCKED)` statement, so concurrent claimers
  skip rows another claimer holds and never claim the same execution twice.
- Every other transaction takes one transaction-scoped advisory lock (per database schema) on
  its first operation, so state transitions run one at a time, exactly like SQLite's
  `BEGIN IMMEDIATE`. The scheduler's read-modify-write steps (join tokens, loop counters, run
  status) therefore need no retry loop. Isolation is READ COMMITTED: after the lock is held,
  every statement sees everything committed before it.
- Fencing is unchanged: `update_execution(expect_status=, expect_epoch=)` is a conditional
  UPDATE; READ COMMITTED re-checks the condition on the newest row version.

psycopg 3 is an optional dependency (`agentline[postgres]`), imported on first use.
"""

